const I18N = {
    _current: null,
    _default: 'en',
    _languages: {},

    init() {
        const saved = localStorage.getItem('tg_viewer_lang');
        if (saved && this._languages[saved]) {
            this._current = saved;
        } else {
            const navLang = (navigator.language || navigator.userLanguage || '').slice(0, 2).toLowerCase();
            this._current = this._languages[navLang] ? navLang : this._default;
        }
    },

    register(langCode, translations) {
        this._languages[langCode] = translations;
    },

    t(key, ...args) {
        if (!this._current) this.init();
        const dict = this._languages[this._current] || this._languages[this._default] || {};
        let str = dict[key] || (this._languages[this._default] && this._languages[this._default][key]) || key;
        args.forEach((arg, i) => { str = str.replace(`{${i}}`, arg); });
        return str;
    },

    setLang(langCode) {
        if (!this._languages[langCode]) return;
        this._current = langCode;
        localStorage.setItem('tg_viewer_lang', langCode);
        document.documentElement.lang = langCode;
        this.applyAll();
        document.dispatchEvent(new Event('languageChanged'));
    },

    getAvailableLanguages() {
        return Object.keys(this._languages).map(code => ({
            code,
            name: this._languages[code]['lang_name'] || code.toUpperCase()
        }));
    },

    lang() {
        if (!this._current) this.init();
        return this._current;
    },

    locale() {
        const map = { en: 'en-US', ru: 'ru-RU' };
        return map[this.lang()] || 'en-US';
    },

    plural(n, forms) {
        const num = Math.abs(Number(n)) || 0;
        const lang = this.lang();
        if (lang === 'ru') {
            const mod10 = num % 10;
            const mod100 = num % 100;
            if (mod10 === 1 && mod100 !== 11) {
                return forms[0] || forms.one;
            } else if (mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20)) {
                return forms[1] || forms.few;
            } else {
                return forms[2] || forms.many;
            }
        }
        return num === 1 ? (forms[0] || forms.one) : (forms[1] || forms.many || forms.other);
    },

    applyAll() {
        document.querySelectorAll('[data-i18n]').forEach(el => {
            el.textContent = this.t(el.dataset.i18n);
        });
        document.querySelectorAll('[data-i18n-html]').forEach(el => {
            el.innerHTML = this.t(el.dataset.i18nHtml);
        });
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            el.placeholder = this.t(el.dataset.i18nPlaceholder);
        });
        document.querySelectorAll('[data-i18n-title]').forEach(el => {
            el.title = this.t(el.dataset.i18nTitle);
        });
        document.querySelectorAll('[data-i18n-label]').forEach(el => {
            el.label = this.t(el.dataset.i18nLabel);
        });
        document.querySelectorAll('[data-i18n-aria]').forEach(el => {
            el.setAttribute('aria-label', this.t(el.dataset.i18nAria));
        });
        const langSelect = document.getElementById('settings-lang-select');
        if (langSelect) langSelect.value = this.lang();
    }
};

